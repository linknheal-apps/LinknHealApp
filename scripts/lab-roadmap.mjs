// scripts/lab-roadmap.mjs  (zero dependencies, Node 18+)
//
// Normal run (automatic, at the end of every `npm run lab`):
//   node scripts/lab-roadmap.mjs
//   Reads  docs/lab/app-map.lab.json + evidence/latest/results.json + evidence/latest/mutations.json
//   Writes docs/lab/ROADMAP.lab.json (project-roadmap schema) and docs/lab/lab-roadmap.csv
//
// Milestone run (manual, only at a big step):
//   node scripts/lab-roadmap.mjs --milestone M-A-thin-slice
//   Does the normal run, then saves a snapshot and writes a PROPOSAL file
//   docs/lab/milestones/<name>.md. It NEVER edits the main docs/ROADMAP.json or APP_MAP.md.
//   A human (Ahmed) or Claude applies the proposal in a reviewed PR.
//
// Status is computed, never typed. An agent's report changes nothing here.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const MAP = 'docs/lab/app-map.lab.json';
const RESULTS = 'evidence/latest/results.json';
const MUTATIONS = 'evidence/latest/mutations.json';
const OUT_JSON = 'docs/lab/ROADMAP.lab.json';
const OUT_CSV = 'docs/lab/lab-roadmap.csv';
const SNAP_DIR = 'docs/lab/snapshots';
const MS_DIR = 'docs/lab/milestones';

const readJson = (p, fallback) => {
  try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return fallback; }
};
const exists = (p) => fs.existsSync(p);

// ---- inputs ---------------------------------------------------------------
const map = readJson(MAP, null);
if (!map) { console.error(`Missing or invalid ${MAP}`); process.exit(1); }
const results = readJson(RESULTS, { tests: [], migrationHash: null });
const mutations = readJson(MUTATIONS, { mutations: [] });

const testStatus = new Map((results.tests || []).map((t) => [t.id, t.status]));
const mutStatus = new Map((mutations.mutations || []).map((m) => [m.id, m.class]));

function migrationHash() {
  const dir = 'supabase/migrations';
  if (!exists(dir)) return null;
  const h = crypto.createHash('sha256');
  for (const f of fs.readdirSync(dir).sort()) h.update(f).update(fs.readFileSync(path.join(dir, f)));
  return h.digest('hex');
}
const curHash = migrationHash();
const evidenceFresh = !!results.migrationHash && results.migrationHash === curHash;

// ---- status computation ---------------------------------------------------
const byId = new Map(map.features.map((f) => [f.id, f]));
const memo = new Map();

function compute(f) {
  if (memo.has(f.id)) return memo.get(f.id);
  memo.set(f.id, { status: 'planned', why: 'cycle guard' }); // cycle guard
  let r;
  const blocked = (f.blocked_by || []);
  const files = f.files || [];
  const have = files.filter(exists).length;

  if (blocked.length) {
    r = { status: 'blocked', why: `blocked by ${blocked.join(', ')}` };
  } else if (have === 0) {
    r = { status: 'planned', why: 'no files yet' };
  } else if (have < files.length) {
    r = { status: 'in_progress', why: `${have}/${files.length} files exist` };
  } else {
    const missing = [];
    const ids = f.tests || [];
    if (ids.length === 0) missing.push('no linked tests');
    for (const id of ids) {
      const s = testStatus.get(id);
      if (s === undefined) missing.push(`${id} not run`);
      else if (s !== 'pass') missing.push(`${id} ${s}`);
    }
    for (const m of f.requires_mutation_kill || []) {
      const c = mutStatus.get(m);
      if (c !== 'KILLED') missing.push(`${m} ${c || 'not run'}`);
    }
    if (!evidenceFresh) missing.push('evidence not bound to current migrations');
    for (const d of f.depends_on || []) {
      const dep = byId.get(d);
      if (dep && compute(dep).status !== 'verified') missing.push(`depends on ${d}`);
    }
    r = missing.length
      ? { status: 'built', why: `built, not verified: ${missing.slice(0, 4).join('; ')}${missing.length > 4 ? '...' : ''}` }
      : { status: 'verified', why: `all ${ids.length} tests pass, mutants killed, evidence fresh` };
  }
  memo.set(f.id, r);
  return r;
}

const computed = map.features.map((f) => ({ f, ...compute(f) }));

// ---- roadmap schema (project-roadmap skill) -------------------------------
// verified -> d ; built -> u (agents cannot make d) ; in_progress -> g ; planned/blocked -> t
const CODE = { verified: 'd', built: 'u', in_progress: 'g', planned: 't', blocked: 't' };
const groups = new Map();
for (const c of computed) {
  if (!groups.has(c.f.group)) groups.set(c.f.group, []);
  groups.get(c.f.group).push([`${c.f.id} ${c.f.name}`, CODE[c.status], c.why]);
}
const count = (s) => computed.filter((c) => c.status === s).length;
const roadmap = {
  _readme: [
    'GENERATED by scripts/lab-roadmap.mjs. Do not edit by hand.',
    'built = files exist (claimed). verified = tests pass + mutants killed + evidence fresh (proven).',
  ],
  name: 'Link & Heal Adversarial Lab',
  asof: new Date().toISOString().slice(0, 10),
  _counters: {
    claimed_built_or_better: count('built') + count('verified'),
    verified_by_ci: count('verified'),
    blocked: count('blocked'),
    total: computed.length,
    evidence_fresh: evidenceFresh,
  },
  phases: [...groups].map(([t, k]) => ({ t, r: '', k })),
};

fs.mkdirSync(path.dirname(OUT_JSON), { recursive: true });
fs.writeFileSync(OUT_JSON, JSON.stringify(roadmap, null, 2));
fs.writeFileSync(
  OUT_CSV,
  ['id,group,status,why']
    .concat(computed.map((c) => [c.f.id, c.f.group, c.status, c.why].map((v) => `"${String(v).replace(/"/g, '""')}"`).join(',')))
    .join('\n')
);

const ct = roadmap._counters;
console.log(`Lab roadmap: claimed ${ct.claimed_built_or_better}/${ct.total}, verified by CI ${ct.verified_by_ci}/${ct.total}, blocked ${ct.blocked}. Evidence fresh: ${ct.evidence_fresh}`);

// ---- milestone mode -------------------------------------------------------
const i = process.argv.indexOf('--milestone');
if (i !== -1) {
  const name = process.argv[i + 1];
  if (!name || !/^[A-Za-z0-9._-]+$/.test(name)) { console.error('Usage: --milestone <name> (letters, digits, . _ -)'); process.exit(1); }
  fs.mkdirSync(SNAP_DIR, { recursive: true });
  fs.mkdirSync(MS_DIR, { recursive: true });
  const prevFile = exists(SNAP_DIR) ? fs.readdirSync(SNAP_DIR).sort().pop() : null;
  const prev = prevFile ? readJson(path.join(SNAP_DIR, prevFile), {}) : {};
  const now = Object.fromEntries(computed.map((c) => [c.f.id, c.status]));
  fs.writeFileSync(path.join(SNAP_DIR, `${new Date().toISOString().slice(0, 10)}-${name}.json`), JSON.stringify(now, null, 2));

  const newly = computed.filter((c) => c.status === 'verified' && prev[c.f.id] !== 'verified');
  const regress = computed.filter((c) => prev[c.f.id] === 'verified' && c.status !== 'verified');
  const lines = [
    `# Milestone proposal: ${name}`,
    '',
    `Generated ${new Date().toISOString()}. This file is a PROPOSAL. Nothing in docs/ROADMAP.json or APP_MAP.md was changed.`,
    '',
    `Counters: claimed ${ct.claimed_built_or_better}/${ct.total}, verified by CI ${ct.verified_by_ci}/${ct.total}, blocked ${ct.blocked}. Evidence fresh: ${ct.evidence_fresh}.`,
    '',
    '## Newly verified since last milestone',
    ...(newly.length ? newly.map((c) => `- ${c.f.id} ${c.f.name}`) : ['- none']),
    '',
    '## Regressions (were verified, are not now)',
    ...(regress.length ? regress.map((c) => `- ${c.f.id}: ${c.why}`) : ['- none']),
    '',
    '## Apply in a reviewed PR (human or Claude, never an agent alone)',
    '- [ ] docs/ROADMAP.json: add or update the single "Adversarial Lab" entry with the counters above and the evidence folder name',
    '- [ ] APP_MAP.md: update the lab node and any edge or matrix row that changed (see list above)',
    '- [ ] Re-run Claude verification on the raw evidence folder before ticking anything',
  ];
  fs.writeFileSync(path.join(MS_DIR, `${name}.md`), lines.join('\n'));
  console.log(`Milestone proposal written: ${path.join(MS_DIR, name + '.md')}`);
}
